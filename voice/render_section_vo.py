"""Render one script section's narration in a reference voice, with word timings for the video.

    .venv\\Scripts\\python.exe render_section_vo.py --script ..\\scripts\\ten-commandments-1-no-other-gods.md
        --section 0 --ref reference\\my-voice\\clean.wav --out ..\\videos\\ten-commandments\\1-cold-open

Writes <out>.wav and <out>-words.js (WORDS = [[word, start, end], ...]). Each "> " paragraph
is split into short passages, rendered with a few seeds, and the take whose pace is closest
to natural is kept. Word times are spread across each passage by word length, which is
close enough to cue animation and subtitles. Pause markers ([beat], [pause], [hold]) become
silence and are never sent to the model.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

import render_full
from generate import PRESETS, Narrator

PAUSES = {"[beat]": 0.3, "[pause]": 0.8, "[hold]": 1.5}
PARAGRAPH_GAP = 0.6
SEEDS = (1, 2, 3, 4)
LEAD_IN = 0.4


def section_paragraphs(script: Path, number: int) -> list[str]:
    source = script.read_text(encoding="utf-8")
    match = re.search(rf"^## {number}\. .*?$(.*?)(?=^## |\Z)", source, re.M | re.S)
    if not match:
        sys.exit(f"No section {number} in {script.name}")
    paragraphs = [line[2:].strip() for line in match.group(1).splitlines() if line.startswith("> ")]
    if any("{{ESV" in p for p in paragraphs):
        sys.exit(f"Section {number} has ESV references. Fill the script with fill_esv.py first.")
    return paragraphs


def best_take(narrator: Narrator, text: str, setting, ref: Path, work: Path) -> tuple[np.ndarray, int]:
    words = len(text.split())
    target = (render_full.MIN_WPS + render_full.MAX_WPS) / 2
    best = None
    for seed in SEEDS:
        path = work / f"take-{abs(hash(text)) % 10**8}-{seed}.wav"
        narrator.synthesize(text, setting, path, seed=seed, voice_ref=ref)
        audio, sr = sf.read(str(path), dtype="float32")
        audio = render_full.trim(audio, sr)
        wps = words / (len(audio) / sr)
        print(f"  seed {seed}: {wps:.2f} words/s", flush=True)
        if best is None or abs(wps - target) < abs(best[2] - target):
            best = (audio, sr, wps)
        if render_full.MIN_WPS <= wps <= render_full.MAX_WPS:
            break
    return best[0], best[1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--script", type=Path, required=True)
    parser.add_argument("--section", type=int, required=True)
    parser.add_argument("--ref", type=Path, required=True, help="A clean recording of your own voice.")
    parser.add_argument("--out", type=Path, required=True, help="Output path without extension.")
    parser.add_argument("--preset", choices=sorted(PRESETS), default="restrained")
    args = parser.parse_args()

    paragraphs = section_paragraphs(args.script, args.section)
    work = args.out.parent / (args.out.name + "-takes")
    work.mkdir(parents=True, exist_ok=True)
    narrator = Narrator()
    setting = PRESETS[args.preset]

    sr = None
    parts: list[np.ndarray] = []
    words: list[list] = []
    cursor = LEAD_IN
    for paragraph in paragraphs:
        if paragraph in PAUSES:
            parts.append(("gap", PAUSES[paragraph]))
            cursor += PAUSES[paragraph]
            continue
        for passage in render_full.chunk(render_full.to_speech(paragraph)):
            print(f"[{cursor:6.2f}s] {passage}", flush=True)
            audio, sr = best_take(narrator, passage, setting, args.ref, work)
            seconds = len(audio) / sr
            tokens = passage.split()
            weights = np.array([len(re.sub(r"[^\w']", "", w)) + 1 for w in tokens], dtype=float)
            edges = np.concatenate([[0], np.cumsum(weights) / weights.sum()]) * seconds
            for i, token in enumerate(tokens):
                words.append([token, round(cursor + edges[i], 3), round(cursor + edges[i + 1], 3)])
            parts.append(audio)
            cursor += seconds + render_full.CHUNK_GAP
            parts.append(("gap", render_full.CHUNK_GAP))
        parts.append(("gap", PARAGRAPH_GAP))
        cursor += PARAGRAPH_GAP

    pieces = [np.zeros(int(LEAD_IN * sr), dtype=np.float32)]
    for part in parts:
        pieces.append(np.zeros(int(part[1] * sr), dtype=np.float32) if isinstance(part, tuple) else part)
    full = np.concatenate(pieces)
    full *= render_full.PEAK / np.abs(full).max()

    args.out.parent.mkdir(parents=True, exist_ok=True)
    sf.write(str(args.out.with_suffix(".wav")), full, sr, subtype="PCM_16")
    js = f"// Generated by voice/render_section_vo.py. [word, start, end] in seconds.\nconst WORDS={json.dumps(words)};\n"
    Path(str(args.out) + "-words.js").write_text(js, encoding="utf-8")
    print(f"DONE {len(full) / sr:.1f} s, {len(words)} words -> {args.out.with_suffix('.wav')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
