function camAt(t){
  let i=0;while(i<CAMK.length-2&&CAMK[i+1][0]<=t)i++;
  const A=CAMK[i],B=CAMK[i+1],d=B[0]-A[0],p=d<1e-6?1:ease.inOut(clamp((t-A[0])/d));
  // A slow handheld drift on top, so nothing is ever fully still.
  return {x:lerp(A[1],B[1],p)+Math.sin(t*.27)*14,y:lerp(A[2],B[2],p)+Math.cos(t*.31)*9,z:lerp(A[3],B[3],p)*(1+.025*Math.sin(t*.35))};
}
